/**
 * The capability catalogue.
 *
 * Every entry is a *claim about this build*, not a wish list. `availability` is
 * the static truth (what the repository can do today); the live probe in
 * `/api/agents/studio/capabilities` can only confirm or lower it — never
 * silently raise a static `unsupported` to `ready`.
 *
 * Anything that is not wired end to end is marked `needs-setup` with the exact
 * fix, so the studio can show a blocked configuration instead of a working-
 * looking toggle.
 */

