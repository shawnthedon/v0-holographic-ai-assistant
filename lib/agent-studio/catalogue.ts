export const CAPABILITY_BY_ID: Record<string, Capability> = Object.fromEntries(
  CAPABILITIES.map((capability) => [capability.id, capability]),
);

export function capabilitiesIn(category: Capability['category']): Capability[] {
  return CAPABILITIES.filter((capability) => capability.category === category);
}

/** The single-select categories: exactly one of these makes sense per agent. */
export const SINGLE_SELECT_CATEGORIES = ['framework', 'model', 'behaviour', 'memory', 'permissions'] as const;

export function isSingleSelect(category: string): boolean {
  return (SINGLE_SELECT_CATEGORIES as readonly string[]).includes(category);
}

