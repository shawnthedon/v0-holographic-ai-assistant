import { NextRequest, NextResponse } from 'next/server';

import { getBrowserService } from '@/lib/browser/service';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

/**
 * Evidence screenshots.
 *
 * GET /api/browser/tasks/:id/screenshot/:screenshotId → image/png
 *
 * These are the frames the agent actually captured when it recorded a milestone;
 * nothing is re-rendered for the UI. A missing file is a 404, never a placeholder.
 */

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ taskId: string; screenshotId: string }> },
) {
  const { taskId, screenshotId } = await params;
  // Both ids are generated by the runner; reject anything that is not one of ours
  // so a crafted path cannot walk out of the evidence directory.
  if (!/^[A-Za-z0-9._-]+$/.test(taskId) || !/^[A-Za-z0-9._-]+$/.test(screenshotId)) {
    return NextResponse.json(
      { error: 'invalid id', code: 'invalid-target', fix: 'Screenshot ids come from the task timeline.' },
      { status: 400 },
    );
  }

  const base64 = await getBrowserService().screenshot(taskId, screenshotId);
  if (!base64) {
    return NextResponse.json(
      { error: 'screenshot not found', code: 'task-not-found', fix: 'The evidence may have been pruned with the task.' },
      { status: 404 },
    );
  }

  const bytes = Buffer.from(base64, 'base64');
  return new NextResponse(new Uint8Array(bytes), {
    status: 200,
    headers: {
      'Content-Type': 'image/png',
      'Cache-Control': 'private, max-age=60',
    },
  });
}
